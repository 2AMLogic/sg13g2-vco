#!/usr/bin/env bash
# Smoke bench for design/vco_core.spice: instantiate the subcircuit with
# VDD=3.3, VSS=0, VCTRL=1.65 and compare its oscillation frequency with the
# flat bench design/vco.spice at the same single nominal point.
#
#   design/run_core_smoke.sh [VSS_VOLTS]     (default VSS = 0)
#
# Method: one `tran 1p 20n 0 2p` per netlist, from the same 10 mV differential
# .ic, f from rising zero crossings of v(OUTP)-v(OUTN) over 10-20 ns
# (sim/lib.sh osc_metrics, ~50 periods), so the count carries +-1 period of
# 50 (about 2 %) and the two runs agree to the first order if the circuits are
# identical. Two ngspice runs, both local, single corner. This is design-
# arithmetic evidence that the subcircuit wrapper preserves the topology; it
# is NOT a spec-row result, covers no PVT corner and makes no phase-noise claim.
#
# A non-zero VSS shifts the supply/control/.ic by VSS: with the bulk on VSS the
# oscillation must follow as a rail shift only (design/README.md).
#
# Requires what design/run_elaborate.sh requires (ngspice, awk, OSDI build).
set -euo pipefail

DESIGN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${DESIGN_DIR}/.." && pwd)"
SIM_DIR="${REPO_ROOT}/sim"
VSS="${1:-0}"

# shellcheck source=../sim/env.sh
source "${SIM_DIR}/env.sh"
# shellcheck source=../sim/lib.sh
source "${SIM_DIR}/lib.sh"

"${DESIGN_DIR}/netlist.sh" --check
"${SIM_DIR}/tools/build-osdi.sh"
OSDI_MOSVAR="${SG13G2_OSDI_DIR}/mosvar.osdi"
IND_MODEL="${SIM_DIR}/inductor-model/sg13g2_inductor_em.spice"

# shellcheck disable=SC2034  # read by lib.sh's make_scratch_workdir
EXPERIMENT_DIR="${DESIGN_DIR}"
make_scratch_workdir "sg13g2-vco-core-smoke"

# Flat reference: the committed bench, tokens substituted, single corner only.
sed -e "s|@@MODELS_DIR@@|${SG13G2_NGSPICE_MODELS}|g" \
    -e "s|@@IND_MODEL@@|${IND_MODEL}|g" \
    -e "s|@@OSDI_MOSVAR@@|${OSDI_MOSVAR}|g" \
    -e 's|^foreach vv .*|foreach vv 1.65|' \
    "${DESIGN_DIR}/vco.spice" > "${WORKDIR}/flat.spice"

# Subcircuit bench: the consumer contract from design/README.md -- models and
# OSDI from the parent, supplies from the parent, startup kick from the parent.
cat > "${WORKDIR}/core.spice" <<DECK
* design/vco_core.spice smoke bench (generated by design/run_core_smoke.sh)
.lib ${SG13G2_NGSPICE_MODELS}/cornerHBT.lib hbt_typ
.lib ${SG13G2_NGSPICE_MODELS}/cornerMOShv.lib mos_tt
.lib ${SG13G2_NGSPICE_MODELS}/cornerCAP.lib cap_typ
.include ${IND_MODEL}
.include ${DESIGN_DIR}/vco_core.spice
XDUT VCTRL OUTP OUTN VDD VSS vco_core
VSUP VDD 0 dc {3.3 + ${VSS}}
VSSS VSS 0 dc ${VSS}
VCT VCTRL 0 dc {1.65 + ${VSS}}
.ic v(OUTP)={3.305 + ${VSS}} v(OUTN)={3.295 + ${VSS}}
.control
pre_osdi ${OSDI_MOSVAR}
save v(OUTP) v(OUTN)
tran 1p 20n 0 2p
let vdiff = v(OUTP) - v(OUTN)
wrdata core_tran vdiff
.endc
.end
DECK

( cd "${WORKDIR}" && ngspice -b flat.spice ) >"${WORKDIR}/flat.log" 2>&1 || true
( cd "${WORKDIR}" && ngspice -b core.spice ) >"${WORKDIR}/core.log" 2>&1 || true

for f in vco_tran_1.65 core_tran; do
  if [[ ! -s "${WORKDIR}/${f}" ]]; then
    echo "error: no waveform ${f}; the transient did not run. Tail of log:" >&2
    tail -15 "${WORKDIR}/${f%%_*}.log" 2>/dev/null >&2 || true
    exit 1
  fi
done

read -r f_flat vpp_flat cyc_flat _ <<<"$(osc_metrics "${WORKDIR}/vco_tran_1.65" 10e-9)"
read -r f_core vpp_core cyc_core _ <<<"$(osc_metrics "${WORKDIR}/core_tran" 10e-9)"

echo "flat  bench : f = ${f_flat} Hz  Vpp = ${vpp_flat} V  cycles = ${cyc_flat}"
echo "vco_core    : f = ${f_core} Hz  Vpp = ${vpp_core} V  cycles = ${cyc_core}  (VSS = ${VSS} V)"
awk -v a="${f_flat}" -v b="${f_core}" -v n="${cyc_flat}" 'BEGIN {
  tol = (n > 0) ? 1.0/n : 0.05
  d = (a > 0) ? (b - a) / a : 1
  if (d < 0) d = -d
  printf "relative difference %.4f  (tolerance 1 period in %d = %.4f): %s\n", d, n, tol, (d <= tol) ? "PASS" : "FAIL"
  exit (d <= tol) ? 0 : 1
}'
